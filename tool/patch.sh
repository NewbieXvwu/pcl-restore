if [ -t 0 ]; then
  printf '输入 0 查看完整许可证内容，其他键继续（直接回车开始）：' >&2
  read -r _viewlic || _viewlic=""
  if [ "$_viewlic" = "0" ]; then
    echo >&2
    if [ -f "$DIR/../LICENCE" ]; then
      cat "$DIR/../LICENCE" >&2
    else
      echo '（未找到 LICENCE 文件，请见仓库根目录）' >&2
    fi
    printf '\n按回车继续...' >&2
    read -r _dummy || true
  fi
  echo >&2
fi

# Applies the IL rewrite to a PCL EXE on macOS/Linux. The input is never modified.
#   usage: patch.sh <input.exe> [output.exe]

IN="${1:?usage: patch.sh <input.exe> [output.exe]}"
OUT="${2:-${IN%.exe}.restored.exe}"

DOTNET="${DOTNET:-dotnet}"
DLL="$DIR/bin/Release/net8.0/PclRestore.dll"
if [ ! -f "$DLL" ]; then
  echo "Tool not built yet. Run $DIR/build.sh first." >&2
  exit 1
fi

"$DOTNET" "$DLL" "$IN" "$OUT"
echo "Restored EXE: $OUT"
